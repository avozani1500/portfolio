import { mkdir, unlink, writeFile } from 'node:fs/promises';

const siteUrl = (process.env.SITE_URL ?? '').replace(/\/$/, '');
if (siteUrl && !/^https?:\/\//i.test(siteUrl)) {
  throw new Error('SITE_URL deve começar com http:// ou https://.');
}

await writeFile(
  'src/app/content/site-url.generated.ts',
  `// Generated by npm run seo:generate. Keep the public URL in SITE_URL.\nexport const generatedSiteUrl = ${JSON.stringify(siteUrl)};\n`,
);

if (!siteUrl) {
  await unlink('public/sitemap.xml').catch(() => undefined);
  await mkdir('public', { recursive: true });
  await writeFile('public/robots.txt', 'User-agent: *\nAllow: /\n');
  console.log('SITE_URL não definido; sitemap.xml não foi gerado para evitar URLs inválidas.');
  process.exit(0);
}

const paths = ['/', '/projetos', '/projetos/item-rarity', '/projetos/baito-barbearia', '/projetos/clinic-management'];
const urls = paths.map((path) => `  <url><loc>${siteUrl}${path}</loc></url>`).join('\n');
await mkdir('public', { recursive: true });
await writeFile('public/sitemap.xml', `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls}\n</urlset>\n`);
await writeFile('public/robots.txt', `User-agent: *\nAllow: /\nSitemap: ${siteUrl}/sitemap.xml\n`);
console.log(`SEO público gerado para ${siteUrl}`);
